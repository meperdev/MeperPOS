-- Retire the abandoned "location foundation" lineage before the multi-site chain.
--
-- On 2026-11-22 two migrations from an unmerged branch were applied to
-- production with a local `prisma migrate deploy`:
--   20261120120000_add_location_foundation
--   20261120130000_add_location_assignments
-- They created "Location", "LocationType", "LocationAssignment", two triggers,
-- two functions and two unique indexes. No released code ever read or wrote
-- them; their rows were produced only by their own backfill and triggers. The
-- multi-site chain that starts at 20261118120000_initial_organization_location
-- creates "Location" and "LocationType" with its own shape, so it cannot apply
-- on top of them (2026-11-27 incident: the deploy failed and the API crashed).
--
-- This migration sorts before that chain, so `prisma migrate deploy` runs it
-- first. It acts only when the abandoned lineage is recorded as applied and the
-- multi-site chain is not; everywhere else (fresh databases, CI, development,
-- databases already on the multi-site chain) it changes nothing.
--
-- Before dropping anything it proves the objects hold only what the abandoned
-- triggers generate: one principal "Sede principal" STORE per organization and
-- principal assignments. Anything else (a second site, a renamed site, a foreign
-- key from another table) aborts the migration instead of discarding data.

-- No explicit BEGIN/COMMIT: Prisma sends the file as one script, which
-- PostgreSQL runs as a single implicit transaction, so a refusal below still
-- rolls everything back, and Prisma reports the refusal's own message instead
-- of "current transaction is aborted".

-- Do not queue writers indefinitely behind the table locks below.
DO $$
BEGIN
    IF (SELECT setting::int FROM pg_catalog.pg_settings WHERE name = 'lock_timeout') NOT BETWEEN 1 AND 5000 THEN
        PERFORM set_config('lock_timeout', '5s', true);
    END IF;
END $$;

DO $$
DECLARE
    abandoned_applied boolean;
    multisite_applied boolean;
    unexpected_locations bigint;
    unexpected_assignments bigint;
    foreign_references bigint;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM "_prisma_migrations"
        WHERE migration_name = '20261120120000_add_location_foundation'
          AND finished_at IS NOT NULL
          AND rolled_back_at IS NULL
    ) INTO abandoned_applied;

    SELECT EXISTS (
        SELECT 1 FROM "_prisma_migrations"
        WHERE migration_name = '20261118120000_initial_organization_location'
          AND finished_at IS NOT NULL
          AND rolled_back_at IS NULL
    ) INTO multisite_applied;

    IF NOT abandoned_applied OR multisite_applied THEN
        RAISE NOTICE 'retire_abandoned_location_lineage: nothing to retire';
        RETURN;
    END IF;

    -- Parent before child, the order organization deletion and provisioning use.
    LOCK TABLE "Organization" IN SHARE ROW EXCLUSIVE MODE;
    LOCK TABLE "OrganizationUser" IN SHARE ROW EXCLUSIVE MODE;
    LOCK TABLE "Location" IN ACCESS EXCLUSIVE MODE;
    IF to_regclass('public."LocationAssignment"') IS NOT NULL THEN
        LOCK TABLE "LocationAssignment" IN ACCESS EXCLUSIVE MODE;
    END IF;

    -- Only trigger-generated sites: the principal store of each organization.
    SELECT count(*) INTO unexpected_locations
    FROM "Location" l
    WHERE NOT (l."isDefault" AND l."type"::text = 'STORE' AND l."name" = 'Sede principal');
    IF unexpected_locations > 0 THEN
        RAISE EXCEPTION 'retire_abandoned_location_lineage: % location row(s) were not generated by the abandoned triggers; review them before deploying', unexpected_locations;
    END IF;

    -- Only principal assignments, each inside its own organization.
    IF to_regclass('public."LocationAssignment"') IS NOT NULL THEN
        EXECUTE $q$
            SELECT count(*)
            FROM "LocationAssignment" a
            LEFT JOIN "Location" l
              ON l."id" = a."locationId" AND l."organizationId" = a."organizationId"
            WHERE l."id" IS NULL OR NOT l."isDefault"
        $q$ INTO unexpected_assignments;
        IF unexpected_assignments > 0 THEN
            RAISE EXCEPTION 'retire_abandoned_location_lineage: % assignment row(s) do not point at a principal site; review them before deploying', unexpected_assignments;
        END IF;
    END IF;

    -- Nothing else may depend on the abandoned "Location".
    SELECT count(*) INTO foreign_references
    FROM pg_constraint c
    WHERE c.contype = 'f'
      AND c.confrelid = 'public."Location"'::regclass
      AND c.conrelid <> COALESCE(to_regclass('public."LocationAssignment"'), 0::regclass);
    IF foreign_references > 0 THEN
        RAISE EXCEPTION 'retire_abandoned_location_lineage: % foreign key(s) from other tables reference "Location"; review them before deploying', foreign_references;
    END IF;

    DROP TRIGGER IF EXISTS "OrganizationUser_principal_location_assignment" ON "OrganizationUser";
    DROP TRIGGER IF EXISTS "Organization_default_location" ON "Organization";
    DROP FUNCTION IF EXISTS "create_principal_location_assignment"();
    DROP FUNCTION IF EXISTS "create_default_organization_location"();
    DROP TABLE IF EXISTS "LocationAssignment";
    DROP TABLE "Location";
    DROP TYPE IF EXISTS "LocationType";
    -- Created by the abandoned lineage; the schema declares no such constraint.
    DROP INDEX IF EXISTS "OrganizationUser_id_organizationId_key";

    RAISE NOTICE 'retire_abandoned_location_lineage: abandoned location lineage retired';
END $$;
