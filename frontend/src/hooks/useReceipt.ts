"use client";

import { api } from "@/lib/api";

interface ReceiptPdf {
  blob: Blob;
  filename: string;
}

async function fetchReceiptPdf(saleId: string): Promise<ReceiptPdf> {
  try {
    const { blob, filename } = await api.fetchBlob(
      `/sales/${saleId}/receipt`,
      {},
    );
    return {
      blob:
        blob.type === "application/pdf"
          ? blob
          : new Blob([blob], { type: "application/pdf" }),
      // Keep a meaningful name when a proxy strips Content-Disposition.
      filename: filename.startsWith("export_")
        ? "comprobante.pdf"
        : filename,
    };
  } catch {
    throw new Error("Error al generar el comprobante");
  }
}

/** Downloads the receipt PDF generated by the backend. */
export async function downloadReceiptPdf(saleId: string): Promise<void> {
  const { blob, filename } = await fetchReceiptPdf(saleId);
  api.saveBlob(blob, filename);
}

/**
 * Opens the receipt PDF in a new tab so the user can review it before
 * printing. Printing uses the browser's PDF viewer, which keeps the printed
 * output identical to the downloaded document.
 */
export async function openReceiptPdf(saleId: string): Promise<void> {
  // Reserve the tab synchronously so popup blockers see a user gesture; the
  // PDF is fetched afterwards and injected into that tab.
  const receiptWindow = window.open("", "_blank");

  if (!receiptWindow) {
    throw new Error(
      "Permita las ventanas emergentes para ver el comprobante",
    );
  }

  receiptWindow.opener = null;

  try {
    const { blob } = await fetchReceiptPdf(saleId);
    const url = window.URL.createObjectURL(blob);
    receiptWindow.location.href = url;
    window.setTimeout(() => window.URL.revokeObjectURL(url), 60_000);
  } catch (error) {
    receiptWindow.close();
    throw error;
  }
}
